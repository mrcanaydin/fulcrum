function dropMigrationTables(ConnectionInterface $db): void
{
    foreach (migrationTables() as $table) {
        $db->statement("DROP TABLE IF EXISTS {$table}");
    }
}

function tableExists(ConnectionInterface $db, string $table): bool
{
    if ($db instanceof PostgresDriver) {
        return $db->select(
            'SELECT table_name FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = ?',
            [$table]
        )->first() !== null;
    }

    return $db->select(
        'SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = ?',
        [$table]
    )->first() !== null;
}

/**
 * @param callable(DatabaseManager): void $callback
 */
function withMigrationSandbox(string $driver, callable $callback): void
{
    $manager = relationalDatabase($driver);
    $connection = $manager->connection();

    if ($connection instanceof PostgresDriver) {
        $schema = 'fulcrum_integration_' . bin2hex(random_bytes(6));
        $connection->statement("CREATE SCHEMA {$schema}");
        $connection->statement("SET search_path TO {$schema}");

        try {
            $callback($manager);
        } finally {
            $connection->statement('SET search_path TO public');
            $connection->statement("DROP SCHEMA IF EXISTS {$schema} CASCADE");
        }

        return;
    }

    dropMigrationTables($connection);

    try {
        $callback($manager);
    } finally {
        dropMigrationTables($connection);
    }
}

/**
 * @param list<string> $expectedTables
 */
function exerciseMigrationPath(string $driver, string $path, array $expectedTables): void
{
    withMigrationSandbox($driver, function (DatabaseManager $manager) use ($path, $expectedTables): void {
        $migrator = new Migrator(new MigrationRepository($manager));
        $ran = $migrator->run($path);

        expect($ran)->not->toBeEmpty();

        foreach ($expectedTables as $table) {
            expect(tableExists($manager->connection(), $table))->toBeTrue("Expected table [{$table}] to exist.");
        }

        $status = $migrator->status($path);
        expect($status)->not->toBeEmpty();

        foreach ($status as $row) {
            expect($row['ran'])->toBeTrue("Expected migration [{$row['migration']}] to be marked as ran.");
        }

        $rolledBack = $migrator->rollback($path);
        expect($rolledBack)->toHaveCount(count($ran));

        foreach ($expectedTables as $table) {
            expect(tableExists($manager->connection(), $table))->toBeFalse("Expected table [{$table}] to be rolled back.");
        }
    });
}

function exerciseDatabaseQueue(string $driver): void
{
    withMigrationSandbox($driver, function (DatabaseManager $manager): void {
        $migrator = new Migrator(new MigrationRepository($manager));
        $migrator->run(__DIR__ . '/../../src/Fulcrum/Queue/Migrations');

        $queue = new DatabaseQueue($manager, 'jobs', 'integration', 'failed_jobs', 1);
        $queue->push(new IntegrationProbeJob('first'));

        expect($queue->size())->toBe(1);

        $firstClaim = $queue->pop();
        expect($firstClaim)->not->toBeNull()
            ->and($firstClaim?->attempts)->toBe(1)
            ->and($firstClaim?->job)->toBeInstanceOf(IntegrationProbeJob::class)
            ->and($queue->pop())->toBeNull();

        if ($firstClaim === null) {
            return;
        }

        $queue->release($firstClaim, 0);

        $secondClaim = $queue->pop();
        expect($secondClaim)->not->toBeNull()
            ->and($secondClaim?->id)->toBe($firstClaim->id)
            ->and($secondClaim?->attempts)->toBe(2);

        if ($secondClaim === null) {
            return;
        }

        $queue->fail($secondClaim, new RuntimeException('failed intentionally'));

        expect($queue->size())->toBe(0)
            ->and($queue->failedCount())->toBe(1);
    });
}

