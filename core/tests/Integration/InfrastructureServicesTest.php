function envString(string $key, string $default): string
{
    $value = getenv($key);

    return is_string($value) && $value !== '' ? $value : $default;
}

function envInt(string $key, int $default): int
{
    $value = getenv($key);

    return is_string($value) && $value !== '' ? (int) $value : $default;
}

function migrationIntegrationTestsEnabled(): bool
{
    return getenv('FULCRUM_TEST_MIGRATIONS') === '1';
}

function relationalDatabase(string $driver): DatabaseManager
{
    $config = integrationConfig();
    $config->set('database.default', $driver);

    if ($driver === 'pgsql') {
        $config->set('database.connections.pgsql', [
            'driver' => 'pgsql',
            'host' => envString('FULCRUM_PGSQL_HOST', '127.0.0.1'),
            'port' => envInt('FULCRUM_PGSQL_PORT', 5432),
            'database' => envString('FULCRUM_PGSQL_DATABASE', 'fulcrum_ci'),
            'username' => envString('FULCRUM_PGSQL_USERNAME', 'fulcrum'),
            'password' => envString('FULCRUM_PGSQL_PASSWORD', 'secret'),
            'prefix' => '',
        ]);
    }

    if ($driver === 'mysql') {
        $config->set('database.connections.mysql', [
            'driver' => 'mysql',
            'host' => envString('FULCRUM_MYSQL_HOST', '127.0.0.1'),
            'port' => envInt('FULCRUM_MYSQL_PORT', 3306),
            'database' => envString('FULCRUM_MYSQL_DATABASE', 'fulcrum_ci'),
            'username' => envString('FULCRUM_MYSQL_USERNAME', 'fulcrum'),
            'password' => envString('FULCRUM_MYSQL_PASSWORD', 'secret'),
            'charset' => 'utf8mb4',
            'prefix' => '',
        ]);
    }

    return new DatabaseManager($config);
}

function exerciseRelationalDatabase(string $driver): void
{
    $db = relationalDatabase($driver)->connection();
    $table = 'fulcrum_integration_' . bin2hex(random_bytes(6));
    $idColumn = $driver === 'pgsql'
        ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
        : 'BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY';

    $db->statement("CREATE TABLE {$table} (id {$idColumn}, name VARCHAR(255) NOT NULL)");

    try {
        $id = $db->table($table)->insert(['name' => 'Ada']);
        $row = $db->table($table)->where('id', $id)->first();

        expect($row)->toBeArray()
            ->and($row['name'] ?? null)->toBe('Ada');
    } finally {
        $db->statement("DROP TABLE IF EXISTS {$table}");
    }
}

function exerciseTransactionBehavior(string $driver): void
{
    $db = relationalDatabase($driver)->connection();
    $table = 'fulcrum_tx_' . bin2hex(random_bytes(6));
    $idColumn = $driver === 'pgsql'
        ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
        : 'BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY';
    $afterCommitCalls = 0;

    $db->statement("CREATE TABLE {$table} (id {$idColumn}, name VARCHAR(255) NOT NULL)");

    try {
        $db->transaction(function () use ($db, $table, &$afterCommitCalls): void {
            $db->table($table)->insert(['name' => 'committed']);
            $db->afterCommit(function () use (&$afterCommitCalls): void {
                $afterCommitCalls++;
            });
        });

        expect($afterCommitCalls)->toBe(1)
            ->and($db->table($table)->where('name', 'committed')->first())->toBeArray();

        try {
            $db->transaction(function () use ($db, $table): void {
                $db->table($table)->insert(['name' => 'rolled_back']);

                throw new RuntimeException('rollback probe');
            });
        } catch (RuntimeException $exception) {
            expect($exception->getMessage())->toBe('rollback probe');
        }

        expect($db->table($table)->where('name', 'rolled_back')->first())->toBeNull();
    } finally {
        $db->statement("DROP TABLE IF EXISTS {$table}");
    }
}

