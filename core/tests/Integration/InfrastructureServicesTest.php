it('connects to a real Redis cache', function () {
    if (getenv('FULCRUM_TEST_REDIS') !== '1') {
        $this->markTestSkipped('Set FULCRUM_TEST_REDIS=1 to run Redis integration tests.');
    }

    $config = integrationConfig();
    $config->set('cache.default', 'redis');
    $config->set('cache.stores.redis', [
        'driver' => 'redis',
        'host' => envString('FULCRUM_REDIS_HOST', '127.0.0.1'),
        'port' => envInt('FULCRUM_REDIS_PORT', 6379),
        'database' => envInt('FULCRUM_REDIS_DATABASE', 0),
        'prefix' => 'fulcrum:integration:',
    ]);

    $cache = (new CacheManager($config))->store();
    $key = 'probe:' . bin2hex(random_bytes(6));

    try {
        $cache->put($key, 'ok', 30);

        expect($cache->get($key))->toBe('ok')
            ->and($cache->increment($key . ':count', 2, 30))->toBe(2);
    } finally {
        $cache->forget($key);
        $cache->forget($key . ':count');
    }
});

